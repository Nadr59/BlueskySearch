        fun getMethodById(id: String): AnalysisMethod? {
            return getAllMethods().find { it.id == id }
        }

        fun buildCombinedPrompt(methods: List<AnalysisMethod>): String {
            if (methods.size == 1) {
                return methods.first().prompt
            }

            return buildString {
                appendLine("حلل هذه الصورة حسب المناهج المحددة أدناه.")
                appendLine("أجب باللغة العربية.")
                appendLine("لكل منهج قسم منفصل بعنوان واضح.")
                appendLine("استخدم التنسيق التالي بالضبط:")
                appendLine()
                appendLine("═══ [اسم المنهج] ═══")
                appendLine("[محتوى التحليل]")
                appendLine()
                appendLine("ميّز في كل قسم بين الحقائق الظاهرة والاستنتاجات.")
                appendLine()
                appendLine("المناهج المطلوبة:")
                appendLine()

                methods.forEach { method ->
                    appendLine("═══ ${method.nameAr} ═══")
                    appendLine(method.prompt)
                    appendLine()
                }
            }
        }

        fun parseSections(response: String, methods: List<AnalysisMethod>): Map<String, String> {
            val results = mutableMapOf<String, String>()

            if (methods.size == 1) {
                results[methods.first().id] = response.trim()
                return results
            }

            for (method in methods) {
                val marker = "═══ ${method.nameAr} ═══"
                val altMarker = "═══${method.nameAr}═══"
                val altMarker2 = "### ${method.nameAr} ###"

                val start = response.indexOf(marker)
                    .takeIf { it != -1 }
                    ?: response.indexOf(altMarker).takeIf { it != -1 }
                    ?: response.indexOf(altMarker2).takeIf { it != -1 }
                    ?: response.indexOf(method.nameAr).takeIf { it != -1 }
                    ?: -1

                if (start != -1) {
                    val markerEnd = response.indexOf("═══", start + marker.length)
                        .takeIf { it != -1 && it > start + marker.length }
                        ?: response.indexOf("###", start + marker.length)
                            .takeIf { it != -1 && it > start + marker.length }

                    val contentStart = response.indexOf("\n", start) + 1
                    val end = markerEnd ?: response.length
                    val content = response.substring(contentStart, end).trim()
                    if (content.isNotBlank()) {
                        results[method.id] = content
                    }
                }
            }

            // إذا لم يتم العثور على أقسام — أضف النص كامل للمنهج الأول
            if (results.isEmpty() && methods.isNotEmpty()) {
                results[methods.first().id] = response.trim()
            }

            return results
        }
    }
